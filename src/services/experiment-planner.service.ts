import { LLMClient } from '../llm/llm.client';
import { ExperimentContext } from '../schemas/experiment.schema';
import {
  experimentPlanSchema,
  ExperimentPlan,
  INSUFFICIENT_CONTEXT,
  validatePlanBusinessRules
} from '../schemas/experiment-plan.schema';
import { AppError } from '../utils/errors';
import { logger } from '../utils/logger';

const SYSTEM_PROMPT = `You are an API experiment planner.

Given a debugging hypothesis and known application/API context,
produce a structured experiment plan.

Your output must contain only valid JSON matching the
ExperimentPlan schema.

The plan must test the hypothesis using the smallest
reproducible set of API testcases and assertions.

Do not generate shell commands.
Do not generate Python.
Do not generate JavaScript.
Do not execute SQL.
Do not invent APIs.
Do not invent database tables.
Do not claim a hypothesis is true.
Design an experiment that could provide evidence for or against it.

Only assert on response fields you have direct evidence for -- from the
hypothesis text, the testcase's own expectedOutput, or a response
example/schema you were given. Do not invent conventional-sounding fields
(e.g. "success", "token", "user.email") just because the API looks like
an authentication API. HTTP status and fields you can justify from
evidence are always safer than guessed body fields.

Mark an assertion "critical": false when it is a supplementary/secondary
check (e.g. an exact response message) rather than the primary evidence
for the hypothesis (e.g. HTTP status). Omit "critical" (defaults to true)
for assertions that must hold for the hypothesis to be supported.

If insufficient information exists to identify a valid target API,
return the JSON string "INSUFFICIENT_CONTEXT" (and nothing else).

Required JSON shape:
{
  "hypothesis": string,
  "experimentType": "API" | "FLOW" | "CONCURRENCY" | "MOCK",
  "objective": string,
  "testcases": [{
    "name": string,
    "description": string,
    "method": get|post|put|patch|delete,
    "url": string,
    "headers": object (optional),
    "params": object (optional),
    "body": object (optional),
    "expectedOutput": object,
    "delay": number (optional),
    "extract": [{ "responsePath": string, "variableName": string }] (optional)
  }],
  "flow": { "name": string, "testcaseOrder": number[] },
  "execution": { "concurrency": number },
  "assertions": [{ "type": "HTTP_STATUS"|"RESPONSE_FIELD"|"DB_COUNT"|"DB_VALUE", "expected": any, "query": string (optional), "field": string (optional), "testcaseIndex": number (optional), "critical": boolean (optional) }]
}`;

export interface PlannerInput {
  hypothesis: string;
  context?: ExperimentContext;
}

function buildUserPrompt(input: PlannerInput): string {
  return JSON.stringify(
    {
      hypothesis: input.hypothesis,
      context: input.context ?? {}
    },
    null,
    2
  );
}

function stripCodeFences(text: string): string {
  const trimmed = text.trim();
  const fenceMatch = trimmed.match(/^```(?:json)?\s*([\s\S]*?)\s*```$/i);
  return fenceMatch ? fenceMatch[1] : trimmed;
}

/** LLMs are inconsistent about HTTP method casing; the QA framework and plan schema require uppercase. */
function normalizeMethod(method: unknown): string {
  const normalized = String(method).trim().toUpperCase();

  const allowed = ['GET', 'PUT', 'POST', 'PATCH', 'DELETE'];

  if (!allowed.includes(normalized)) {
    throw AppError.badGateway(
      'LLM_INVALID_OUTPUT',
      `Unsupported HTTP method generated by experiment planner: ${method}`
    );
  }

  return normalized;
}

/** Mutates parsed.testcases[].method in place so schema validation sees a consistent case. */
function normalizePlanMethods(parsed: unknown): void {
  if (!parsed || typeof parsed !== 'object' || !Array.isArray((parsed as { testcases?: unknown }).testcases)) {
    return;
  }

  for (const testcase of (parsed as { testcases: unknown[] }).testcases) {
    if (testcase && typeof testcase === 'object' && 'method' in testcase) {
      (testcase as { method: unknown }).method = normalizeMethod((testcase as { method: unknown }).method);
    }
  }
}

/**
 * Layer 1 of the architecture: Hypothesis -> GLM-5 -> structured
 * ExperimentPlan. This is the ONLY place the LLM is invoked. Everything
 * downstream (Layer 2 compilation, Layer 3 execution) works exclusively
 * off the validated ExperimentPlan object, never off raw model output.
 */
export class ExperimentPlanner {
  constructor(private readonly llm: LLMClient) {}

  async plan(input: PlannerInput): Promise<ExperimentPlan> {
    const completion = await this.llm.complete({
      messages: [
        { role: 'system', content: SYSTEM_PROMPT },
        { role: 'user', content: buildUserPrompt(input) }
      ],
      temperature: 0.1,
      jsonMode: true
    });

    const cleaned = stripCodeFences(completion.text);

    if (cleaned.replace(/^"|"$/g, '') === INSUFFICIENT_CONTEXT) {
      throw AppError.badRequest(
        'INSUFFICIENT_CONTEXT',
        'The model could not identify a valid target API/endpoint from the given hypothesis and context. Provide more context (service, endpoint, method).'
      );
    }

    let parsed: unknown;
    try {
      parsed = JSON.parse(cleaned);
    } catch (err) {
      logger.error({ msg: 'Failed to parse LLM output as JSON', error: (err as Error).message });
      throw AppError.badGateway('LLM_INVALID_OUTPUT', 'LLM did not return valid JSON');
    }

    if (typeof parsed === 'string' && parsed === INSUFFICIENT_CONTEXT) {
      throw AppError.badRequest(
        'INSUFFICIENT_CONTEXT',
        'The model could not identify a valid target API/endpoint from the given hypothesis and context.'
      );
    }

    normalizePlanMethods(parsed);

    const result = experimentPlanSchema.safeParse(parsed);
    if (!result.success) {
      logger.error({ msg: 'LLM output failed schema validation', issues: result.error.issues });
      throw AppError.badRequest('INVALID_EXPERIMENT_PLAN', 'Generated experiment plan failed schema validation', {
        issues: result.error.issues
      });
    }

    // Business + security validation (allow-listed hosts, injection scan,
    // concurrency/testcase caps) -- runs before ANY compilation step.
    validatePlanBusinessRules(result.data);

    logger.info({
      operation: 'experiment.plan',
      generatedPlan: result.data
    });
    return result.data;
  }
}
